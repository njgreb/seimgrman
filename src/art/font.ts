export const FONT_KEY = 'font';
export const CHAR_W = 6;
export const CHAR_H = 8;
const CHARS = Object.keys(GLYPHS).join('');

export function createFont(scene: Phaser.Scene): void {
  const tex = scene.textures.createCanvas('font-src', CHARS.length * CHAR_W, CHAR_H)!;
  const ctx = tex.getContext();
  ctx.fillStyle = '#ffffff';
  [...CHARS].forEach((ch, i) => {
    GLYPHS[ch].forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row & (1 << (4 - x))) ctx.fillRect(i * CHAR_W + x, y, 1, 1);
    });
  });
  tex.refresh();

  const config = {
    image: 'font-src',
    width: CHAR_W,
    height: CHAR_H,
    chars: CHARS,
    charsPerRow: CHARS.length,
    spacing: { x: 0, y: 0 },
    offset: { x: 0, y: 0 },
    lineSpacing: 2,
  };
  const data = Phaser.GameObjects.RetroFont.Parse(scene, config as unknown as Phaser.Types.GameObjects.BitmapText.RetroFontConfig);
  scene.cache.bitmapFont.add(FONT_KEY, data);
}
